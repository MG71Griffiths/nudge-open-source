const assert=require('node:assert/strict');
const composition=require('../Web/core/food-composition.js');
const component=(definition,grams=100)=>({amountGrams:grams,sourceRecord:{carbohydrateDefinition:definition},nutrients:{carbohydrate:{value:10},protein:{value:2},fibre:{value:3},energyKcal:{value:40}}});
const mixed=composition.total([component('available'),component('by_difference_including_fibre')]);
assert.equal(mixed.carbohydrate.value,null);
assert.equal(mixed.carbohydrate.knownSubtotal,10,'Retain only the compatible available-carbohydrate subtotal');
assert.equal(mixed.carbohydrate.knownContributions,1);
assert.equal(mixed.carbohydrate.unknownContributions,1);
assert.match(mixed.carbohydrate.missingReason,/incompatible source definitions are excluded/);
assert.deepEqual(composition.total([component('by_difference_including_fibre'),component('available')]),mixed,'Source order cannot change the selected basis');
assert.equal(mixed.protein.value,4);
assert.equal(mixed.fibre.value,6);
assert.equal(mixed.energyKcal.value,80);
assert.equal(composition.total([component('by_difference_including_fibre'),component(undefined)]).carbohydrate.value,null);
assert.equal(composition.total([component('by_difference_including_fibre'),component(undefined)]).carbohydrate.knownSubtotal,10);
const unknownSeasoning={amountGrams:null,nutrients:{}};
assert.equal(composition.total([component('by_difference_including_fibre'),unknownSeasoning]).carbohydrate.knownSubtotal,10,'An unknown seasoning cannot erase all sourced carbohydrate');
assert.equal(composition.total([component('available'),unknownSeasoning]).carbohydrate.unknownContributions,1);
assert.equal(composition.total([component('by_difference_including_fibre'),component('by_difference_including_fibre',50)]).carbohydrate.value,15);
assert.equal(composition.total([component('available'),component('available',50)]).carbohydrate.value,15);
assert.equal(composition.total([component(undefined),component(undefined,50)]).carbohydrate.value,15,'Legacy records retain their recorded basis');
assert.equal(composition.value('Tr').value,null);
assert.equal(composition.value('N').value,null);
assert.equal(composition.value('0').value,0);
console.log('PASS: carbohydrate definitions are not mixed; compatible and legacy bases, protein/fibre/energy and unknown/trace/zero remain correct.');
