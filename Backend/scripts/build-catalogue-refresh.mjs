// Rebuild after a shared scoring/evidence-engine change. The generated runner
// has no package installation or repository-runtime dependency on GitHub.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { relative, resolve } from 'node:path';
const require = createRequire(realpathSync(new URL('../node_modules/wrangler/package.json', import.meta.url)));
const { build } = require('esbuild');
const root = fileURLToPath(new URL('../../', import.meta.url));
const outfile = fileURLToPath(new URL('./catalogue-refresh-cli.mjs', import.meta.url));
const result = await build({
  absWorkingDir: root,
  entryPoints: [fileURLToPath(new URL('./import-off-catalogue.mjs', import.meta.url))],
  outfile, metafile: true,
  bundle: true, platform: 'node', target: 'node22', format: 'esm',
  banner: {js: '// Generated by build-catalogue-refresh.mjs. Shared source remains authoritative.'},
  legalComments: 'inline'
});
const sha256 = data => createHash('sha256').update(data).digest('hex');
const sources = {};
for (const input of Object.keys(result.metafile.inputs).sort()) {
  const path = relative(root, resolve(root, input));
  if (path.startsWith('..') || path.includes('node_modules')) throw new Error('Unexpected catalogue runner dependency: ' + path);
  sources[path] = sha256(await readFile(resolve(root, path)));
}
// The cloud runner needs no install/build step. Source hashes record this
// build snapshot even when the runner repository has a different app revision.
await writeFile(new URL('./catalogue-refresh-cli.sources.json', import.meta.url), JSON.stringify({
  version: 1, bundle: relative(root, outfile), sha256: sha256(await readFile(outfile)), sources
}, null, 2) + '\n');
